// Builds supabase/deploy/send-notifications.single.ts: the Edge Function as ONE file, for pasting into the
// Supabase dashboard editor (which can't take several files). Source of truth is supabase/functions/send-notifications/.
// Usage: npm run build:function
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const dir = 'supabase/functions/send-notifications/'
const read = f => readFileSync(dir + f, 'utf8')
const stripExport = s => s.replace(/^export /gm, '')

const logic = read('logic.ts')
const notify = read('notify.ts').replace(/import \{[^}]*\} from '\.\/logic\.ts'\n/s, '')
const [, indexBody] = read('index.ts')
  .replace(/import type \{[^\n]*\} from '\.\/logic\.ts'\n/, '')
  .replace(/import \{ runTick[^\n]*\n/, '')
  .split("import webpush from 'npm:web-push@3.6.7'\n")

const out =
  "import { createClient } from 'npm:@supabase/supabase-js@2'\nimport webpush from 'npm:web-push@3.6.7'\n\n" +
  '// GENERATED by scripts/build-edge-function.mjs - do not edit; edit supabase/functions/send-notifications/ instead.\n' +
  '// ---- logic ----\n' + stripExport(logic) +
  '\n// ---- orchestration ----\n' + stripExport(notify) +
  '\n// ---- entry point ----\n' + indexBody

mkdirSync('supabase/deploy', { recursive: true })
writeFileSync('supabase/deploy/send-notifications.single.ts', out)
console.log(`wrote supabase/deploy/send-notifications.single.ts (${out.length} chars)`)
